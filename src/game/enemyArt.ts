export const ENEMY_SIZE = Object.fromEntries(
  Object.entries(ENEMY_ART).map(([type, [body, legs]]) => [
    type,
    { w: Math.max(...[...body, ...legs].map((r) => r.length)), h: body.length + legs.length },
  ]),
) as Record<EnemyType, { w: number; h: number }>;
